inline std::vector<std::complex<float>> make_zadoff_chu(int length, int root) {
    std::vector<std::complex<float>> u(static_cast<std::size_t>(length));
    const double n_len = static_cast<double>(length);
    for (int n = 0; n < length; ++n) {
        // Odd length: n(n+1); even length: n^2.  Reduce mod 2N before
        // multiplying by pi to keep precision.
        const long long q = (length % 2) ? static_cast<long long>(n) * (n + 1)
                                         : static_cast<long long>(n) * n;
        const long long m = (static_cast<long long>(root) * q) % (2LL * length);
        const double ph = -3.14159265358979323846 * static_cast<double>(m) / n_len;
        u[static_cast<std::size_t>(n)] = {static_cast<float>(std::cos(ph)),
                                          static_cast<float>(std::sin(ph))};
    }
    return u;
}

inline std::vector<std::complex<float>> default_unique_word() {
    return {UNIQUE_WORD_SPEC_TABLE.begin(), UNIQUE_WORD_SPEC_TABLE.end()};
}

